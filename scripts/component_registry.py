def _canonical_registry_file(
    registry_path: Path,
    *,
    root: Path,
) -> Path:
    expected = (
        root / "framework" / "component-registry.json"
    ).resolve()
    try:
        relative = (
            registry_path.relative_to(root)
            if registry_path.is_absolute()
            else registry_path
        )
    except ValueError as exc:
        raise RegistryError("registry is outside the repository authority") from exc
    resolved = _contained_file(root, relative, "registry")
    if resolved != expected:
        raise RegistryError(
            "candidate refresh is restricted to the canonical Component Registry"
        )
    return resolved


def _refresh_pinned_document_digests(
    registry: dict[str, Any],
    *,
    root: Path,
) -> dict[str, str]:
    refreshed: dict[str, str] = {}
    entries = registry["operational_documents"]["entries"]
    for identity, entry in entries.items():
        if entry["digest_policy"] != "pinned":
            continue
        path = _contained_file(
            root,
            entry["canonical_path"],
            f"document {identity}",
        )
        digest = _sha256(path)
        entry["sha256"] = digest
        refreshed[identity] = digest
    return refreshed


def _candidate_route_hash_drift_untyped(
    candidate_route: Mapping[str, Any],
    live_route: Mapping[str, Any],
) -> list[str]:
    structural_keys = ROUTE_SOURCE_KEYS - {"documents"}
    structural_drift = [
        key
        for key in sorted(structural_keys)
        if canonical_json(candidate_route[key])
        != canonical_json(live_route[key])
    ]
    if structural_drift:
        raise RegistryError(
            "candidate refresh cannot accept structural route drift: "
            + ", ".join(structural_drift)
        )
    candidate_documents = candidate_route["documents"]
    live_documents = live_route["documents"]
    if set(candidate_documents) != set(live_documents):
        raise RegistryError(
            "candidate refresh cannot add or remove routed document identities"
        )
    changed: list[str] = []
    for identity in sorted(candidate_documents):
        before = dict(candidate_documents[identity])
        after = dict(live_documents[identity])
        before_digest = before.pop("sha256", None)
        after_digest = after.pop("sha256", None)
        if canonical_json(before) != canonical_json(after):
            raise RegistryError(
                "candidate refresh cannot accept structural route drift for "
                f"document {identity}"
            )
        if before_digest != after_digest:
            changed.append(identity)
    return changed


def _candidate_route_hash_drift(
    candidate_route: Mapping[str, Any],
    live_route: Mapping[str, Any],
) -> list[str]:
    """Restrict candidate refresh to authorized digest-only currentness."""

    try:
        return _candidate_route_hash_drift_untyped(
            candidate_route,
            live_route,
        )
    except RoutingRuleFailure:
        raise
    except RegistryError as exc:
        raise _routing_rule_failure(
            failure_code="CTXR_UNRESOLVED_MATERIAL_GOVERNING_GAP",
            phase="governance_change",
            rule_ids=(
                "ctxr.cur.checkpoint_update_needs_no_registry_edit",
                "ctxr.budget.ceiling_change_does_not_change_membership",
            ),
            message=f"Component Registry route refresh is invalid: {exc}",
            cause=exc,
        )


def _atomic_write_validated_candidate(
    destination: Path,
    registry: dict[str, Any],
    route: dict[str, Any],
    schema: dict[str, Any],
    *,
    root: Path,
) -> None:
    content = json.dumps(registry, ensure_ascii=False, indent=2) + "\n"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.refresh-",
        dir=destination.parent,
    )
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, destination.stat().st_mode & 0o777)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            descriptor = -1
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        written = _read_json(temporary)
        _validate_against_schema(written, schema, schema)
        if parity_report(written, route)["valid"] is not True:
            raise RegistryError(
                "refreshed candidate failed embedded route parity before write"
            )
        _validate_stage1_semantics(written, route, root=root)
        os.replace(temporary, destination)
    except Exception:
        if descriptor >= 0:
            os.close(descriptor)
        raise


def refresh_candidate_registry(
    registry_path: Path = DEFAULT_REGISTRY,
    *,
    root: Path = ROOT,
    acknowledged_document_ids: Sequence[str] = (),
) -> dict[str, Any]:
    """Refresh exact candidate hashes without granting or activating authority."""

    registry_path = _canonical_registry_file(registry_path, root=root)
    candidate = _read_json(registry_path)
    schema_path = _contained_file(
        root,
        Path("framework") / str(candidate.get("$schema") or ""),
        "registry schema",
    )
    expected_schema = (
        root
        / "framework"
        / "standards"
        / "automation"
        / "component-registry.schema.json"
    ).resolve()
    if schema_path != expected_schema:
        raise RegistryError("candidate registry uses an unapproved schema authority")
    schema = _read_json(schema_path)
    if candidate.get("status") != "candidate":
        raise RegistryError("candidate refresh rejects active registry status")
    _validate_against_schema(candidate, schema, schema)
    _validate_registry_status(candidate)

    source_spec = candidate["context_routing"]["source_import"]
    baseline_spec = candidate["source_baseline"]["route_source"]
    expected_route_path = ROUTING_PREDECESSOR_PATHS[
        "context_routes_source"
    ]["historical_path"]
    if (
        source_spec["path"] != expected_route_path
        or baseline_spec["path"] != expected_route_path
        or source_spec["schema_version"] != baseline_spec["schema_version"]
        or source_spec["sha256"] != baseline_spec["sha256"]
    ):
        raise RegistryError(
            "candidate route source declarations are not one exact baseline"
        )
    route_path = _contained_file(root, expected_route_path, "context route source")
    live_route = _read_json(route_path)
    validate_route_source(live_route)
    try:
        load_route_manifest(route_path, root=root, verify_hashes=True)
    except (ContextError, OSError) as exc:
        raise RegistryError(f"context route source validation failed: {exc}") from exc

    embedded_route = _routing_snapshot(candidate)
    validate_route_source(embedded_route)
    if (
        candidate["context_routing"]["expected_counts"]
        != route_counts(embedded_route)
    ):
        raise RegistryError(
            "candidate embedded route counts differ from its recorded baseline"
        )
    repository_revision = candidate["source_baseline"]["repository_revision"]
    if (
        candidate["source_baseline"]["working_tree_binding"]["sha256"]
        != _route_source_binding(repository_revision, embedded_route)
    ):
        raise RegistryError(
            "candidate working-tree binding differs from its embedded route"
        )
    head = _repository_head(root)
    if head is not None and head != repository_revision:
        raise RegistryError(
            "repository HEAD differs from the candidate source baseline"
        )

    candidate_for_validation = copy.deepcopy(candidate)
    _refresh_pinned_document_digests(candidate_for_validation, root=root)
    _validate_stage1_semantics(
        candidate_for_validation,
        embedded_route,
        root=root,
    )

    changed_document_ids = _candidate_route_hash_drift(
        embedded_route,
        live_route,
    )
    acknowledged = _assert_unique_strings(
        list(acknowledged_document_ids),
        "changed routed document acknowledgements",
    )
    unknown = sorted(set(acknowledged) - set(live_route["documents"]))
    if unknown:
        raise RegistryError(
            f"changed routed document acknowledgements are unknown: {unknown}"
        )
    missing = sorted(set(changed_document_ids) - set(acknowledged))
    extra = sorted(set(acknowledged) - set(changed_document_ids))
    if missing or extra:
        raise RegistryError(
            "changed routed document acknowledgements do not exactly match "
            f"route digest drift; missing={missing}, extra={extra}"
        )

    refreshed = copy.deepcopy(candidate)
    routing = refreshed["context_routing"]
    for key in ROUTE_SOURCE_KEYS:
        if key == "schema_version":
            routing["source_import"]["schema_version"] = live_route[key]
        else:
            routing[key] = copy.deepcopy(live_route[key])
    routing["expected_counts"] = route_counts(live_route)
    route_digest = _sha256(route_path)
    routing["source_import"]["sha256"] = route_digest
    refreshed["source_baseline"]["route_source"] = {
        "path": expected_route_path,
        "sha256": route_digest,
        "schema_version": live_route["schema_version"],
    }
    refreshed["source_baseline"]["working_tree_binding"]["sha256"] = (
        _route_source_binding(repository_revision, live_route)
    )
    refreshed_document_digests = _refresh_pinned_document_digests(
        refreshed,
        root=root,
    )

    _validate_against_schema(refreshed, schema, schema)
    _validate_stage1_semantics(refreshed, live_route, root=root)
    parity = parity_report(refreshed, live_route)
    if not parity["valid"]:
        raise RegistryError(
            "refreshed candidate differs from the exact live route snapshot"
        )
    if routing["source_import"]["sha256"] != _sha256(route_path):
        raise RegistryError("context route source changed during candidate refresh")

    _atomic_write_validated_candidate(
        registry_path,
        refreshed,
        live_route,
        schema,
        root=root,
    )
    validated, validated_route = load_validated_registry(
        registry_path,
        root=root,
    )
    if validated["status"] != "candidate":
        raise RegistryError("candidate refresh cannot activate registry authority")
    return {
        "valid": True,
        "status": validated["status"],
        "authoritative": False,
        "changed_document_ids": changed_document_ids,
        "route_source_sha256": validated["context_routing"]["source_import"][
            "sha256"
        ],
        "source_binding_sha256": validated["source_baseline"][
            "working_tree_binding"
        ]["sha256"],
        "route_counts": route_counts(validated_route),
        "refreshed_operational_document_ids": sorted(
            refreshed_document_digests
        ),
    }


def _validated_component_registry_routing_view(
    registry: Mapping[str, Any],
    *,
    candidate_source_route: Mapping[str, Any] | None = None,
    activation_readback: Mapping[str, Any] | None = None,
    active_configuration_validation_only: bool = False,
    registry_path: str = "framework/component-registry.json",
) -> dict[str, Any]:
    """Build the sole pure routing view for candidate or active consumers.

    Candidate validation remains bound to the exact predecessor route.  An
    adopted active registry rejects predecessor input and consumes only its
    embedded Component Registry route.  This adapter never activates a
    candidate; the separate authenticated activation transaction remains
    human-gated.
    """
    if registry.get("status") == "active":
        if active_configuration_validation_only:
            if activation_readback is not None:
                raise RegistryError(
                    "active configuration validation cannot consume "
                    "activation readback"
                )
        else:
            _validate_active_routing_readback(registry, activation_readback)
        _validate_registry_status(
            registry,
            require_authenticated_activation_readback=False,
        )
    else:
        if active_configuration_validation_only:
            raise RegistryError(
                "candidate routing cannot claim active configuration "
                "validation"
            )
        if activation_readback is not None:
            raise RegistryError(
                "candidate routing cannot consume active activation readback"
            )
        _validate_registry_status(registry)
    _validate_registry_routing_state(registry)
    if registry_path != "framework/component-registry.json":
        raise RegistryError(
            "Component Registry routing requires its canonical registry path"
        )
    embedded = _routing_snapshot(registry)
    validate_route_source(embedded)
    if registry["status"] == "candidate":
        if candidate_source_route is None:
            raise RegistryError(
                "candidate routing requires exact predecessor validation"
            )
        supplied = dict(candidate_source_route)
        validate_route_source(supplied)
        if canonical_json(embedded) != canonical_json(supplied):
            raise RegistryError(
                "candidate routing source and embedded routing disagree"
            )
        mode = "candidate_validation_only"
        predecessor_consulted = True
    else:
        if candidate_source_route is not None:
            raise RegistryError(
                "active Component Registry routing forbids predecessor input "
                "or fallback"
            )
        mode = (
            "active_configuration_validation_only"
            if active_configuration_validation_only
            else "active_component_registry"
        )
        predecessor_consulted = False
    registry_digest = hashlib.sha256(
        canonical_json(registry).encode("utf-8")
    ).hexdigest()
    routing_authority_sha256 = (
        registry["context_routing"]["source_import"]["sha256"]
        if mode == "candidate_validation_only"
        else registry_digest
    )
    return {
        "schema_version": 1,
        "validation_mode": mode,
        "registry_id": registry["registry_id"],
        "registry_revision": registry["registry_revision"],
        "registry_status": registry["status"],
        "registry_sha256": registry_digest,
        "routing_authority_sha256": routing_authority_sha256,
        "registry_path": registry_path,
        "authoritative": mode == "active_component_registry",
        "executable": mode == "active_component_registry",
        "live_activation_verified": mode == "active_component_registry",
        "activation_receipt_consulted": (
            mode == "active_component_registry"
        ),
        "predecessor_route_consulted": predecessor_consulted,
        "route": json.loads(canonical_json(embedded)),
        "_validated_registry": registry,
    }


def validated_component_registry_routing_view(
    registry: Mapping[str, Any],
    *,
    candidate_source_route: Mapping[str, Any],
    registry_path: str = CANONICAL_REGISTRY_PATH,
) -> dict[str, Any]:
    """Validate one in-memory candidate for parity inspection only.

    Active routing is deliberately unavailable through an in-memory public
    adapter.  Production active routing must pass through the fixed
    ProjectPathAuthority reader, and fixture active routing must pass through
    the explicit contained fixture loader.
    """
    if registry.get("status") != "candidate":
        raise RegistryError(
            "active routing is available only through fixed path authority"
        )
    return _validated_component_registry_routing_view(
        registry,
        candidate_source_route=candidate_source_route,
        registry_path=registry_path,
    )


def _routed_selection_from_view_untyped(
    view: Mapping[str, Any],
    registry: Mapping[str, Any],
    *,
    profile_id: str | None,
    capability_ids: Sequence[str],
    selection_kind: str,
    executable: bool,
) -> dict[str, Any]:
    mode = view.get("validation_mode")
    if (
        view.get("schema_version") != 1
        or mode
        not in {
            "candidate_validation_only",
            "active_configuration_validation_only",
            "active_component_registry",
        }
        or not isinstance(view.get("route"), Mapping)
        or view.get("registry_path")
        != CANONICAL_REGISTRY_PATH
    ):
        raise RegistryError(
            "routing view is not a validated Component Registry view"
        )
    expected_mode_state = {
        "candidate_validation_only": {
            "registry_status": "candidate",
            "authoritative": False,
            "executable": False,
            "live_activation_verified": False,
            "activation_receipt_consulted": False,
            "predecessor_route_consulted": True,
        },
        "active_configuration_validation_only": {
            "registry_status": "active",
            "authoritative": False,
            "executable": False,
            "live_activation_verified": False,
            "activation_receipt_consulted": False,
            "predecessor_route_consulted": False,
        },
        "active_component_registry": {
            "registry_status": "active",
            "authoritative": True,
            "executable": True,
            "live_activation_verified": True,
            "activation_receipt_consulted": True,
            "predecessor_route_consulted": False,
        },
    }[str(mode)]
    if any(
        view.get(field) != expected
        for field, expected in expected_mode_state.items()
    ):
        raise RegistryError(
            "routing view authority flags disagree with its validation mode"
        )
    expected_routing_authority_sha256 = (
        registry["context_routing"]["source_import"]["sha256"]
        if mode == "candidate_validation_only"
        else view["registry_sha256"]
    )
    if (
        view.get("routing_authority_sha256")
        != expected_routing_authority_sha256
    ):
        raise RegistryError(
            "routing view authority digest disagrees with its validation mode"
        )
    embedded = view["route"]
    if (
        registry["status"] == "active"
        and (
            mode
            not in {
                "active_configuration_validation_only",
                "active_component_registry",
            }
            or view.get("predecessor_route_consulted") is not False
        )
    ):
        raise RegistryError(
            "active Component Registry routing cannot use predecessor authority"
        )
    if (
        registry["status"] == "candidate"
        and (
            view.get("validation_mode") != "candidate_validation_only"
            or view.get("predecessor_route_consulted") is not True
        )
    ):
        raise RegistryError(
            "candidate routing lacks exact predecessor validation"
        )
    if executable and view.get("executable") is not True:
        raise RegistryError(
            "configuration validation routing cannot satisfy an executable "
            "consumer"
        )
    if executable and (
        not isinstance(profile_id, str)
        or not profile_id.strip()
    ):
        raise RegistryError(
            "executable routing requires exactly one registered primary profile"
        )
    if (
        not executable
        and selection_kind == "capability_preview"
        and profile_id is not None
    ):
        raise RegistryError(
            "capability preview cannot select an executable primary profile"
        )
    if (
        selection_kind == "configuration_validation_packet"
        and (
            executable
            or not isinstance(profile_id, str)
            or not profile_id.strip()
        )
    ):
        raise RegistryError(
            "configuration validation requires one nonexecuting primary "
            "profile"
        )
    documents = embedded["documents"]
    seeds = list(embedded["required_modules"])
    inclusion_reasons: dict[str, set[str]] = {
        identity: {"required floor"} for identity in embedded["required_modules"]
    }
    sections: list[dict[str, Any]] = []
    if profile_id is not None:
        profile = embedded["profiles"].get(profile_id)
        if profile is None:
            raise RegistryError(f"unknown context profile: {profile_id}")
        for identity in profile.get("modules", []):
            seeds.append(identity)
            inclusion_reasons.setdefault(identity, set()).add(
                f"profile {profile_id}"
            )
        for capability in profile.get("capabilities", []):
            for identity in embedded["capabilities"][capability]:
                seeds.append(identity)
                inclusion_reasons.setdefault(identity, set()).add(
                    f"profile {profile_id} capability {capability}"
                )
        if profile.get("include_all_governing"):
            for identity, spec in documents.items():
                if spec["governing"]:
                    seeds.append(identity)
                    inclusion_reasons.setdefault(identity, set()).add(
                        f"profile {profile_id} complete governing boundary"
                    )
        sections.extend(profile.get("sections", []))
    for capability in capability_ids:
        members = embedded["capabilities"].get(capability)
        if members is None:
            raise RegistryError(f"unknown context capability: {capability}")
        for identity in members:
            seeds.append(identity)
            inclusion_reasons.setdefault(identity, set()).add(
                f"requested capability {capability}"
            )
    if profile_id is None and not capability_ids:
        raise RegistryError(
            "capability preview requires at least one registered capability"
        )
    modules = _dependency_closure(documents, seeds)
    for identity in modules:
        for dependency in documents[identity].get("requires", []):
            inclusion_reasons.setdefault(dependency, set()).add(
                f"dependency of {identity}"
            )
    operational_documents = registry["operational_documents"]["entries"]
    return {
        "selection_kind": selection_kind,
        "executable": executable,
        "registry_id": registry["registry_id"],
        "registry_revision": registry["registry_revision"],
        "registry_status": registry["status"],
        "registry_sha256": view["registry_sha256"],
        "registry_path": view["registry_path"],
        "validation_mode": mode,
        "authoritative": executable and view["authoritative"] is True,
        "live_activation_verified": (
            executable and view["live_activation_verified"] is True
        ),
        "activation_receipt_consulted": (
            executable and view["activation_receipt_consulted"] is True
        ),
        "source_sha256": view["routing_authority_sha256"],
        "profile": profile_id,
        "capabilities": list(capability_ids),
        "modules": [
            {
                "id": identity,
                "path": documents[identity]["path"],
                "governing": documents[identity]["governing"],
                "hash_policy": documents[identity]["hash_policy"],
                "sha256": documents[identity].get("sha256"),
                "authority_role": operational_documents[identity][
                    "authority_role"
                ],
                "authority_scope": operational_documents[identity][
                    "purpose_scope"
                ],
                "authority_exclusions": operational_documents[identity][
                    "authority_exclusions"
                ],
                "dependencies": documents[identity].get("requires", []),
                "inclusion_reasons": sorted(
                    inclusion_reasons.get(identity, {"dependency closure"})
                ),
            }
            for identity in modules
        ],
        "sections": sections,
    }


def _routed_selection_from_view(
    view: Mapping[str, Any],
    registry: Mapping[str, Any],
    *,
    profile_id: str | None,
    capability_ids: Sequence[str],
    selection_kind: str,
    executable: bool,
) -> dict[str, Any]:
    """Resolve a selection and retain typed evidence for blocked selection."""

    try:
        return _routed_selection_from_view_untyped(
            view,
            registry,
            profile_id=profile_id,
            capability_ids=capability_ids,
            selection_kind=selection_kind,
            executable=executable,
        )
    except RoutingRuleFailure:
        raise
    except RegistryError as exc:
        detail = str(exc)
        rule_ids = [
            "ctxr.fail.unknown_or_missing_selection",
            "ctxr.sel.primary_profile",
            "ctxr.sel.profile_starting_set",
        ]
        if "capability" in detail:
            rule_ids.append(
                "ctxr.sel.capability_addition_requires_no_new_profile"
            )
        raise _routing_rule_failure(
            failure_code="CTXR_UNKNOWN_OR_MISSING_SELECTION",
            phase="packet_build" if executable else "route_definition",
            rule_ids=rule_ids,
            message=f"Component Registry routing selection is invalid: {detail}",
            cause=exc,
        )


def _validated_registry_from_view(
    view: Mapping[str, Any],
) -> Mapping[str, Any]:
    registry = view.get("_validated_registry")
    if not isinstance(registry, Mapping):
        raise RoutingRuleFailure(
            failure_code="CTXR_UNKNOWN_OR_MISSING_SELECTION",
            phase="registry_state",
            rule_ids=("ctxr.val.registry_before_selection",),
            message=(
                "routing view lacks its validated Component Registry source"
            ),
        )
    if (
        view.get("registry_sha256")
        != hashlib.sha256(
            canonical_json(registry).encode("utf-8")
        ).hexdigest()
    ):
        raise RoutingRuleFailure(
            failure_code="CTXR_PINNED_DIGEST_ABSENT_OR_STALE",
            phase="packet_build",
            rule_ids=("ctxr.val.registry_digest_external",),
            message=(
                "routing view differs from its validated Component Registry "
                "source"
            ),
        )
    return registry


