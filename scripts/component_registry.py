def _registry_alias_source_lines(
    registry: Mapping[str, Any],
    text: str,
) -> set[int]:
    """Locate only structurally registered migration source-path leaves."""

    aliases = registry["aliases_and_migrations"]["entries"]
    lines = text.splitlines()
    result: set[int] = set()
    for alias in aliases.values():
        source_path = alias["source_path"]
        exact_fragment = f'"source_path": {json.dumps(source_path)}'
        matches = {
            number
            for number, line in enumerate(lines, start=1)
            if exact_fragment in line
        }
        if len(matches) != 1:
            raise RegistryError(
                "reference-disposition registry source-path location differs"
            )
        result.update(matches)
    return result


def _predecessor_definition_lines(text: str) -> set[int]:
    """Locate the four typed historical-path constants by Python AST."""

    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        raise RegistryError(
            "reference-disposition Component Registry tool is invalid"
        ) from exc
    assignment: ast.Dict | None = None
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and any(
                isinstance(target, ast.Name)
                and target.id == "ROUTING_PREDECESSOR_PATHS"
                for target in node.targets
            )
            and isinstance(node.value, ast.Dict)
        ):
            assignment = node.value
            break
    if assignment is None:
        raise RegistryError(
            "reference-disposition predecessor definitions are absent"
        )
    locations: dict[str, tuple[str, int]] = {}
    for identity_node, specification_node in zip(
        assignment.keys,
        assignment.values,
        strict=True,
    ):
        identity = ast.literal_eval(identity_node)
        if not isinstance(identity, str) or not isinstance(
            specification_node,
            ast.Dict,
        ):
            continue
        for key_node, value_node in zip(
            specification_node.keys,
            specification_node.values,
            strict=True,
        ):
            key = ast.literal_eval(key_node)
            if key != "historical_path":
                continue
            value = ast.literal_eval(value_node)
            if not isinstance(value, str):
                raise RegistryError(
                    "reference-disposition historical path is invalid"
                )
            locations[identity] = (value, value_node.lineno)
    expected = {
        identity: specification["historical_path"]
        for identity, specification in ROUTING_PREDECESSOR_PATHS.items()
    }
    if (
        set(locations) != set(expected)
        or any(
            locations[identity][0] != path
            for identity, path in expected.items()
        )
    ):
        raise RegistryError(
            "reference-disposition predecessor definitions differ"
        )
    return {line for _, line in locations.values()}


def classify_reference_dispositions(
    items: Sequence[Mapping[str, Any]],
    *,
    root: Path,
    source_revision: str,
    input_manifest: Mapping[str, Any],
) -> list[dict[str, Any]]:
    """Assign the closed 917/59 activation disposition split."""

    manifest_items = input_manifest.get("items")
    if not isinstance(manifest_items, list):
        raise RegistryError(
            "reference-disposition input manifest is incomplete"
        )
    manifest_by_path = {
        str(item["path"]): item
        for item in manifest_items
        if isinstance(item, Mapping)
        and set(item) == {"path", "bytes", "sha256"}
    }
    source_paths = {
        CANONICAL_REGISTRY_PATH,
        "scripts/component_registry.py",
        ROUTING_RULE_CLOSURE_RECEIPT_PATH,
        *(
            specification["historical_path"]
            for specification in ROUTING_PREDECESSOR_PATHS.values()
        ),
    }
    texts: dict[str, str] = {}
    for path in source_paths:
        text = _reference_baseline_text(
            root=root,
            revision=source_revision,
            path=path,
        )
        binding = manifest_by_path.get(path)
        encoded = text.encode("utf-8")
        if (
            binding is None
            or binding.get("bytes") != len(encoded)
            or binding.get("sha256")
            != hashlib.sha256(encoded).hexdigest()
        ):
            raise RegistryError(
                "reference-disposition preserved source binding differs"
            )
        texts[path] = text
    baseline_registry = json.loads(texts[CANONICAL_REGISTRY_PATH])
    registry_source_lines = _registry_alias_source_lines(
        baseline_registry,
        texts[CANONICAL_REGISTRY_PATH],
    )
    predecessor_definition_lines = _predecessor_definition_lines(
        texts["scripts/component_registry.py"]
    )
    aliases = baseline_registry["aliases_and_migrations"]["entries"]
    predecessor_sources = {
        specification["historical_path"]
        for specification in ROUTING_PREDECESSOR_PATHS.values()
    }
    classified: list[dict[str, Any]] = []
    for original in items:
        item = dict(original)
        path = str(item.get("path"))
        line = item.get("line")
        alias_id = item.get("alias_id")
        if (
            not isinstance(line, int)
            or line < 1
            or alias_id not in aliases
            or path not in manifest_by_path
        ):
            raise RegistryError(
                "reference-disposition finding identity is invalid"
            )
        expected_id = hashlib.sha256(
            f"{path}:{line}:{alias_id}".encode("utf-8")
        ).hexdigest()[:16]
        if item.get("reference_id") != expected_id:
            raise RegistryError(
                "reference-disposition finding digest differs"
            )
        if path in texts:
            source_lines = texts[path].splitlines()
            if line > len(source_lines) or (
                aliases[alias_id]["source_path"]
                not in source_lines[line - 1]
            ):
                raise RegistryError(
                    "reference-disposition finding location differs"
                )
        disposition = "rewrite_current"
        if (
            path == CANONICAL_REGISTRY_PATH
            and line in registry_source_lines
        ):
            disposition = "preserve_migration_definition"
        elif (
            path == "scripts/component_registry.py"
            and line in predecessor_definition_lines
        ):
            disposition = "preserve_predecessor_definition"
        elif path == ROUTING_RULE_CLOSURE_RECEIPT_PATH:
            disposition = "preserve_migration_evidence"
        elif path in predecessor_sources:
            disposition = "preserve_exact_predecessor_artifact"
        item["disposition"] = disposition
        classified.append(item)
    counts = dict(
        sorted(Counter(item["disposition"] for item in classified).items())
    )
    if counts != REFERENCE_DISPOSITION_COUNTS:
        raise RegistryError(
            "reference-disposition split differs from the approved 917/59 "
            f"closure: {counts}"
        )
    return classified


def _console_json_payload(
    path: Path,
    *,
    prefix: str,
    suffix: str,
    label: str,
) -> dict[str, Any]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RegistryError(f"{label} is unreadable") from exc
    if not text.startswith(prefix) or not text.endswith(suffix):
        raise RegistryError(f"{label} wrapper differs")
    try:
        value = json.loads(text[len(prefix):-len(suffix)])
    except json.JSONDecodeError as exc:
        raise RegistryError(f"{label} payload is invalid") from exc
    if not isinstance(value, dict):
        raise RegistryError(f"{label} payload must be an object")
    return value


def _console_payload_count(value: object) -> int:
    if isinstance(value, list):
        return len(value)
    if isinstance(value, dict):
        return sum(_console_payload_count(item) for item in value.values())
    return 0


def build_console_generation_readback(
    *,
    root: Path,
) -> dict[str, Any]:
    """Bind the complete generated public Console bundle without private I/O."""

    catalog_path = _contained_file(
        root,
        CONSOLE_CATALOG_PATH,
        "Project Console catalog",
    )
    manifest_path = _contained_file(
        root,
        CONSOLE_GENERATION_MANIFEST_PATH,
        "Project Console generation manifest",
    )
    catalog = _console_json_payload(
        catalog_path,
        prefix=CONSOLE_CATALOG_PREFIX,
        suffix=";\n",
        label="Project Console catalog",
    )
    manifest = _read_json(manifest_path)
    expected_manifest_fields = {
        "manifest_schema_version",
        "generation_id",
        "generated_at",
        "source_revision",
        "availability",
        "completeness",
        "domain_count",
        "domains",
        "files",
    }
    if set(manifest) != expected_manifest_fields:
        raise RegistryError("Project Console generation manifest fields differ")
    completeness = manifest.get("completeness")
    if (
        manifest.get("manifest_schema_version") != 1
        or not isinstance(manifest.get("generation_id"), str)
        or not manifest["generation_id"]
        or not isinstance(manifest.get("source_revision"), str)
        or not manifest["source_revision"]
        or manifest.get("availability") != "current"
        or not isinstance(completeness, Mapping)
        or completeness.get("complete") is not True
        or completeness.get("expected_count")
        != completeness.get("actual_count")
        or completeness.get("missing_count") != 0
    ):
        raise RegistryError("Project Console generation is not current and complete")
    if catalog.get("generation_manifest") != manifest:
        raise RegistryError(
            "Project Console catalog and generation manifest differ"
        )
    for field in (
        "generation_id",
        "generated_at",
        "source_revision",
        "availability",
        "completeness",
    ):
        if catalog.get(field) != manifest.get(field):
            raise RegistryError(
                f"Project Console catalog {field} differs from its manifest"
            )
    source_hashes = catalog.get("source_hashes")
    if not isinstance(source_hashes, Mapping) or not source_hashes:
        raise RegistryError("Project Console source hash map is absent")
    normalized_source_hashes: dict[str, str] = {}
    for label, digest in source_hashes.items():
        if (
            not isinstance(label, str)
            or not label
            or not isinstance(digest, str)
            or re.fullmatch(r"sha256:[0-9a-f]{64}", digest) is None
        ):
            raise RegistryError("Project Console source hash entry is invalid")
        if label == ACTIVATION_READINESS_RECEIPT_PATH:
            raise RegistryError(
                "terminal activation-readiness receipt cannot feed the Console"
            )
        if not label.startswith("feed:"):
            source_path = _contained_file(
                root,
                label,
                "Project Console source",
            )
            if digest != f"sha256:{_sha256(source_path)}":
                raise RegistryError(
                    f"Project Console source hash is stale: {label}"
                )
        normalized_source_hashes[label] = digest
    if REQUIREMENT_CLOSURE_RECEIPT_PATH not in normalized_source_hashes:
        raise RegistryError(
            "Project Console omits the requirement-closure source"
        )

    domains = manifest.get("domains")
    files = manifest.get("files")
    if (
        not isinstance(domains, list)
        or not isinstance(files, Mapping)
        or manifest.get("domain_count") != len(domains)
        or len(domains) != len(files)
    ):
        raise RegistryError("Project Console domain inventory is incomplete")
    domain_readback: list[dict[str, Any]] = []
    domain_names: list[str] = []
    for domain in domains:
        expected_domain_fields = {
            "file",
            "sha256",
            "bytes",
            "keys",
            "record_count",
        }
        if not isinstance(domain, Mapping) or set(domain) != expected_domain_fields:
            raise RegistryError("Project Console domain fields differ")
        name = domain.get("file")
        if (
            not isinstance(name, str)
            or Path(name).name != name
            or not name.endswith(".js")
            or name.startswith("private-")
            or name == "local-automation-status.js"
        ):
            raise RegistryError("Project Console domain filename is invalid")
        if name in domain_names:
            raise RegistryError("Project Console domain filename is duplicated")
        domain_names.append(name)
        relative = f"{CONSOLE_DATA_DIRECTORY}/{name}"
        path = _contained_file(root, relative, "Project Console domain")
        content = path.read_bytes()
        digest = f"sha256:{hashlib.sha256(content).hexdigest()}"
        payload = _console_json_payload(
            path,
            prefix=CONSOLE_DOMAIN_PREFIX,
            suffix=");\n",
            label=f"Project Console domain {name}",
        )
        generation = payload.pop("domain_generation", None)
        if generation != {name: manifest["generation_id"]}:
            raise RegistryError(
                f"Project Console domain generation differs: {name}"
            )
        expected_domain = {
            "file": name,
            "sha256": digest,
            "bytes": len(content),
            "keys": sorted(payload),
            "record_count": _console_payload_count(payload),
        }
        expected_file = {
            "generation_id": manifest["generation_id"],
            **{
                key: value
                for key, value in expected_domain.items()
                if key != "file"
            },
        }
        if dict(domain) != expected_domain:
            raise RegistryError(
                f"Project Console domain manifest differs: {name}"
            )
        if files.get(name) != expected_file:
            raise RegistryError(
                f"Project Console file manifest differs: {name}"
            )
        domain_readback.append(
            {
                "path": relative,
                "bytes": len(content),
                "sha256": digest,
                "record_count": expected_domain["record_count"],
            }
        )

    data_root = (root / CONSOLE_DATA_DIRECTORY).resolve()
    if data_root.is_symlink() or not data_root.is_dir():
        raise RegistryError("Project Console data directory is unavailable")
    actual_public_names = sorted(
        path.name
        for path in data_root.iterdir()
        if path.is_file()
        and not path.name.startswith("private-")
        and path.name != "local-automation-status.js"
    )
    expected_public_names = sorted(
        [Path(CONSOLE_GENERATION_MANIFEST_PATH).name, *domain_names]
    )
    if actual_public_names != expected_public_names:
        raise RegistryError(
            "Project Console generated public file set is not exact"
        )
    return {
        "complete": True,
        "generation_id": manifest["generation_id"],
        "source_revision": manifest["source_revision"],
        "availability": "current",
        "completeness": dict(completeness),
        "catalog": {
            "path": CONSOLE_CATALOG_PATH,
            "bytes": catalog_path.stat().st_size,
            "sha256": f"sha256:{_sha256(catalog_path)}",
        },
        "generation_manifest": {
            "path": CONSOLE_GENERATION_MANIFEST_PATH,
            "bytes": manifest_path.stat().st_size,
            "sha256": f"sha256:{_sha256(manifest_path)}",
        },
        "source_hash_map_sha256": hashlib.sha256(
            canonical_json(dict(sorted(normalized_source_hashes.items()))).encode(
                "utf-8"
            )
        ).hexdigest(),
        "domain_count": len(domain_readback),
        "domains": domain_readback,
        "public_file_set": [
            CONSOLE_CATALOG_PATH,
            CONSOLE_GENERATION_MANIFEST_PATH,
            *[item["path"] for item in domain_readback],
        ],
    }


