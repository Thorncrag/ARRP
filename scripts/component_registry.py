def parity_report(
    registry: Mapping[str, Any],
    source_route: Mapping[str, Any],
) -> dict[str, Any]:
    if registry.get("status") != "candidate":
        raise RegistryError(
            "routing parity is candidate predecessor validation only"
        )
    snapshot = _routing_snapshot(registry)
    differences: list[str] = []
    for key in ROUTE_SOURCE_KEYS:
        if canonical_json(snapshot[key]) != canonical_json(source_route[key]):
            differences.append(key)
    route_ids = sorted(source_route["documents"])
    registry_ids = sorted(snapshot["documents"])
    return {
        "valid": not differences,
        "source_sha256": registry["context_routing"]["source_import"]["sha256"],
        "registry_route_sha256": hashlib.sha256(
            canonical_json(snapshot).encode("utf-8")
        ).hexdigest(),
        "counts": route_counts(snapshot),
        "differences": differences,
        "document_ids_equal": route_ids == registry_ids,
        "profile_ids_equal": sorted(source_route["profiles"])
        == sorted(snapshot["profiles"]),
        "capability_ids_equal": sorted(source_route["capabilities"])
        == sorted(snapshot["capabilities"]),
    }


def load_validated_registry(
    registry_path: Path = DEFAULT_REGISTRY,
    *,
    root: Path = ROOT,
) -> tuple[dict[str, Any], dict[str, Any]]:
    try:
        relative_registry = (
            registry_path.relative_to(root)
            if registry_path.is_absolute()
            else registry_path
        )
    except ValueError as exc:
        raise RegistryError("registry is outside the repository authority") from exc
    registry_path = _contained_file(root, relative_registry, "registry")
    registry = _read_json(registry_path)
    schema_path = _contained_file(
        root,
        Path("framework") / str(registry.get("$schema") or ""),
        "registry schema",
    )
    expected_schema = (
        root
        / "framework"
        / "standards"
        / "automation"
        / "component-registry.schema.json"
    ).resolve()
    if schema_path != expected_schema:
        raise RegistryError("candidate registry uses an unapproved schema authority")
    schema = _read_json(schema_path)
    _validate_against_schema(registry, schema, schema)
    if registry.get("status") != "candidate":
        raise RegistryError(
            "predecessor-bound registry loader accepts candidate state only"
        )
    source_spec = registry["context_routing"]["source_import"]
    baseline_spec = registry["source_baseline"]["route_source"]
    if {
        "path": source_spec["path"],
        "sha256": source_spec["sha256"],
        "schema_version": source_spec["schema_version"],
    } != baseline_spec:
        raise RegistryError("context route import and source baseline disagree")
    source_path = _contained_file(root, source_spec["path"], "context route source")
    actual_digest = _sha256(source_path)
    if actual_digest != source_spec["sha256"]:
        raise RegistryError(
            "context route source digest differs from the candidate baseline"
        )
    route = _read_json(source_path)
    validate_route_source(route)
    try:
        load_route_manifest(source_path, root=root, verify_hashes=True)
    except (ContextError, OSError) as exc:
        raise RegistryError(f"context route source validation failed: {exc}") from exc
    actual_counts = route_counts(route)
    if actual_counts != registry["context_routing"]["expected_counts"]:
        raise RegistryError(
            "context route source counts differ from the candidate baseline"
        )
    head = _repository_head(root)
    repository_revision = registry["source_baseline"]["repository_revision"]
    if head is not None and head != repository_revision:
        raise RegistryError(
            "repository HEAD differs from the candidate source baseline"
        )
    binding = registry["source_baseline"]["working_tree_binding"]
    expected_binding = _route_source_binding(repository_revision, route)
    if binding["sha256"] != expected_binding:
        raise RegistryError(
            "candidate working-tree source binding differs from the routed authority"
        )
    parity = parity_report(registry, route)
    if not parity["valid"]:
        raise RegistryError(
            "embedded context routing differs from the exact source import: "
            + ", ".join(parity["differences"])
        )
    _validate_stage1_semantics(registry, route, root=root)
    return registry, route


def _registry_and_schema_from_authority(
    authority: ProjectPathAuthority,
) -> tuple[Path, dict[str, Any], dict[str, Any]]:
    try:
        registry_path = authority.repository_path(
            CANONICAL_REGISTRY_PATH
        )
        schema_path = authority.repository_path(
            "framework/standards/automation/"
            "component-registry.schema.json"
        )
    except PathAuthorityError as exc:
        raise RegistryError(
            "canonical Component Registry authority is unavailable"
        ) from exc
    registry = _read_json(registry_path)
    if (
        registry.get("$schema")
        != "standards/automation/component-registry.schema.json"
    ):
        raise RegistryError(
            "Component Registry uses an unapproved schema authority"
        )
    schema = _read_json(schema_path)
    _validate_against_schema(registry, schema, schema)
    return registry_path, registry, schema


