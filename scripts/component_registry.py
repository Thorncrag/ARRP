def render_context_routing_rule(
    rule_id: str,
    entry: Mapping[str, Any],
) -> dict[str, Any]:
    """Return one deterministic browser-safe rendering with no prose parsing."""
    dispatched = validate_routing_rule_definition(rule_id, entry)
    predicate_type = dispatched["predicate_type"]
    label = predicate_type.rsplit(".", 1)[-1].replace("_", " ").title()
    parameter_parts: list[str] = []
    for key, value in dispatched["parameters"].items():
        parameter_label = key.replace("_", " ")
        if isinstance(value, list):
            rendered_value = ", ".join(
                str(item).replace("_", " ") for item in value
            )
        elif isinstance(value, bool):
            rendered_value = "true" if value else "false"
        else:
            rendered_value = str(value).replace("_", " ")
        parameter_parts.append(f"{parameter_label}: {rendered_value}")
    rendered_text = label
    if parameter_parts:
        rendered_text += " — " + "; ".join(parameter_parts)
    return {
        **dispatched,
        "label": label,
        "rendered_text": rendered_text,
    }


def _validate_routing_rule_catalog(registry: Mapping[str, Any]) -> None:
    """Fail closed unless all exact v1 rule definitions are valid."""
    routing = registry.get("context_routing")
    if not isinstance(routing, Mapping):
        raise RegistryError("context_routing must be an object")
    expected_context_fields = {
        "candidate": ROUTING_CONTEXT_CANDIDATE_KEYS,
        "active": ROUTING_CONTEXT_ACTIVE_KEYS,
    }.get(str(registry.get("status")))
    if expected_context_fields is None:
        raise RegistryError(
            "context_routing cannot validate an unknown registry state"
        )
    unknown_context_fields = sorted(
        set(routing) - expected_context_fields
    )
    if unknown_context_fields:
        raise RegistryError(
            "context_routing has unknown fields "
            f"{unknown_context_fields}"
        )
    missing_context_fields = sorted(
        expected_context_fields - set(routing)
    )
    if missing_context_fields:
        raise RegistryError(
            "context_routing is missing fields "
            f"{missing_context_fields}"
        )
    if routing.get("schema_version") != 2:
        raise RegistryError("context_routing must use schema_version 2")
    if routing.get("rule_catalog_version") != 1:
        raise RegistryError("context_routing must use rule_catalog_version 1")

    all_rule_ids: list[str] = []
    clause_keys: set[str] = set()
    source_entry = registry["operational_documents"]["entries"].get(
        "context_routing"
    )
    expected_source_digest_policy = (
        "pinned"
        if registry.get("status") == "candidate"
        else "provenance_only"
    )
    if (
        not isinstance(source_entry, Mapping)
        or source_entry.get("digest_policy")
        != expected_source_digest_policy
        or SHA256_RE.fullmatch(str(source_entry.get("sha256") or "")) is None
    ):
        raise RegistryError(
            "routing rule catalog lacks its exact context_routing "
            "source provenance"
        )
    source_sha256 = source_entry["sha256"]

    for map_name in ROUTING_RULE_MAPS:
        rule_map = routing.get(map_name)
        if not isinstance(rule_map, Mapping):
            raise RegistryError(
                f"context_routing.{map_name} must be a closed rule map"
            )
        expected_ids = set(ROUTING_RULE_IDS[map_name])
        actual_ids = set(rule_map)
        missing_ids = sorted(expected_ids - actual_ids)
        unknown_ids = sorted(actual_ids - expected_ids)
        if missing_ids or unknown_ids:
            raise RegistryError(
                f"context_routing.{map_name} rule identities differ "
                f"(missing {missing_ids}, unknown {unknown_ids})"
            )
        all_rule_ids.extend(
            str(entry.get("rule_id") or "")
            for entry in rule_map.values()
            if isinstance(entry, Mapping)
        )
    duplicate_rule_ids = sorted(
        identity
        for identity, count in Counter(all_rule_ids).items()
        if identity and count > 1
    )
    if duplicate_rule_ids:
        raise RegistryError(
            f"routing rule catalog contains duplicate IDs {duplicate_rule_ids}"
        )

    all_rule_ids = []
    for map_name in ROUTING_RULE_MAPS:
        rule_map = routing[map_name]
        for rule_id in ROUTING_RULE_IDS[map_name]:
            entry = rule_map[rule_id]
            if not isinstance(entry, Mapping):
                raise RegistryError(
                    f"routing rule {rule_id}: entry must be an object"
                )
            all_rule_ids.append(str(entry.get("rule_id") or ""))
            expected_keys = set(ROUTING_RULE_ENTRY_KEYS)
            if map_name == "failure_rules":
                expected_keys.add("failure_code")
            actual_keys = set(entry)
            if actual_keys != expected_keys:
                raise RegistryError(
                    f"routing rule {rule_id}: fields differ "
                    f"(missing {sorted(expected_keys - actual_keys)}, "
                    f"unknown {sorted(actual_keys - expected_keys)})"
                )
            if entry.get("rule_id") != rule_id:
                raise RegistryError(
                    f"routing rule {rule_id}: map key and rule_id disagree"
                )
            if entry.get("rule_version") != 1:
                raise RegistryError(
                    f"routing rule {rule_id}: unsupported rule_version"
                )
            if entry.get("status") != "active":
                raise RegistryError(
                    f"routing rule {rule_id}: unsupported status"
                )
            if entry.get("predicate_type") != rule_id:
                raise RegistryError(
                    f"routing rule {rule_id}: predicate_type must equal "
                    "its stable rule ID"
                )
            provenance = entry.get("source_provenance")
            if not isinstance(provenance, Mapping):
                raise RegistryError(
                    f"routing rule {rule_id}: source_provenance must be an object"
                )
            if set(provenance) != ROUTING_RULE_PROVENANCE_KEYS:
                raise RegistryError(
                    f"routing rule {rule_id}: source_provenance fields differ"
                )
            if (
                provenance.get("source_document_id") != "context_routing"
                or provenance.get("source_sha256") != source_sha256
                or not isinstance(provenance.get("source_heading"), str)
                or not provenance["source_heading"].strip()
                or not isinstance(provenance.get("clause_key"), str)
                or not provenance["clause_key"].strip()
                or provenance["clause_key"] != rule_id
            ):
                raise RegistryError(
                    f"routing rule {rule_id}: invalid source_provenance"
                )
            clause_key = provenance["clause_key"]
            if clause_key in clause_keys:
                raise RegistryError(
                    f"routing rule {rule_id}: duplicate clause_key {clause_key}"
                )
            clause_keys.add(clause_key)
            verification_ids = _assert_unique_strings(
                entry.get("verification_ids"),
                f"routing rule {rule_id} verification_ids",
            )
            if verification_ids != [f"test.{rule_id}"]:
                raise RegistryError(
                    f"routing rule {rule_id}: verification_ids do not bind "
                    "the exact rule"
                )
            if map_name == "failure_rules":
                failure_code = entry.get("failure_code")
                if (
                    not isinstance(failure_code, str)
                    or ROUTING_RULE_FAILURE_CODE_RE.fullmatch(failure_code)
                    is None
                    or failure_code != ROUTING_RULE_FAILURE_CODES[rule_id]
                ):
                    raise RegistryError(
                        f"routing rule {rule_id}: invalid failure_code"
                    )
            validate_routing_rule_definition(rule_id, entry)

    expected_count = sum(len(ids) for ids in ROUTING_RULE_IDS.values())
    if len(all_rule_ids) != expected_count:
        raise RegistryError(
            "routing rule catalog does not contain the exact approved 64 rules"
        )
    if set(ROUTING_RULE_DEFINITION_VALIDATORS) != set(all_rule_ids):
        raise RegistryError(
            "routing rule definition validators differ from the catalog"
        )


def render_routing_rules(registry: Mapping[str, Any]) -> str:
    """Render a deterministic nonauthoritative view of typed routing rules."""
    _validate_routing_rule_catalog(registry)
    registry_digest = hashlib.sha256(
        canonical_json(registry).encode("utf-8")
    ).hexdigest()
    lines = [
        "# Generated Context Routing Rules",
        "",
        f"- Registry revision: `{registry['registry_revision']}`",
        f"- Registry SHA-256: `{registry_digest}`",
        "- Authority: `nonauthoritative generated view`",
    ]
    routing = registry["context_routing"]
    for map_name in ROUTING_RULE_MAPS:
        lines.extend(["", f"## {map_name.replace('_', ' ').title()}"])
        for rule_id in ROUTING_RULE_IDS[map_name]:
            rendered = render_context_routing_rule(
                rule_id,
                routing[map_name][rule_id],
            )
            lines.extend(
                [
                    "",
                    f"### {rendered['label']}",
                    "",
                    f"- Rule: {rendered['rendered_text']}",
                    f"- Predicate type: `{rendered['predicate_type']}`",
                    "- Parameters: "
                    f"`{canonical_json(rendered['parameters'])}`",
                ]
            )
    return "\n".join(lines) + "\n"


def _validate_stage1_semantics(
    registry: Mapping[str, Any],
    route: Mapping[str, Any],
    *,
    root: Path = ROOT,
    require_authenticated_activation_readback: bool = True,
) -> None:
    _validate_registry_status(
        registry,
        require_authenticated_activation_readback=(
            require_authenticated_activation_readback
        ),
    )
    _validate_registry_routing_state(registry)
    for namespace in DEFERRED_NAMESPACES:
        if registry.get(namespace) != DEFERRED_ENVELOPE:
            raise RegistryError(
                f"{namespace} must retain the exact deferred non-enforced envelope"
            )
    terminology = registry["terminology"]
    if terminology != {
        "schema_version": 1,
        "activation_state": "candidate_unpopulated",
        "complete": False,
        "entries": {},
    }:
        raise RegistryError(
            "terminology must remain the exact unpopulated candidate namespace"
        )
    _validate_directory_scopes(registry)
    active_registry = registry.get("status") == "active"
    if active_registry:
        _validate_active_predecessor_exclusion(registry, route)
    _validate_operational_documents(
        registry,
        route,
        root=root,
        provenance_only_document_ids=(
            frozenset(ROUTING_PREDECESSOR_IDS)
            if active_registry
            else frozenset()
        ),
    )
    _validate_section_selectors(route, root=root)
    _validate_ownership(registry)
    _validate_relationships_and_representations(registry)
    _validate_scan_exclusion_bindings(registry)
    _validate_aliases(registry)
    _validate_activation_readiness(registry, root=root)
    _validate_repository_refs(registry)
    _validate_routing_rule_catalog(registry)


def _validate_active_predecessor_exclusion(
    registry: Mapping[str, Any],
    route: Mapping[str, Any],
) -> None:
    """Validate frozen predecessor provenance without predecessor file I/O."""
    routing = registry["context_routing"]
    if registry["context_routing"].get("expected_counts") != route_counts(
        route
    ):
        raise RegistryError(
            "active Component Registry routing counts differ from its "
            "embedded authority"
        )
    predecessor_paths = {
        spec["historical_path"]
        for spec in ROUTING_PREDECESSOR_PATHS.values()
    } | {
        spec["archived_path"]
        for spec in ROUTING_PREDECESSOR_PATHS.values()
    }
    routed_predecessors = sorted(
        identity
        for identity, spec in route["documents"].items()
        if identity in ROUTING_PREDECESSOR_IDS
        or spec.get("path") in predecessor_paths
    )
    if routed_predecessors:
        raise RegistryError(
            "active Component Registry routing still selects a predecessor"
        )
    if "source_import" in routing or "parity_policy" in routing:
        raise RegistryError(
            "active Component Registry routing retains candidate predecessor "
            "authority fields"
        )
    baseline = registry.get("source_baseline")
    if not isinstance(baseline, Mapping) or set(baseline) != {
        "repository_revision",
        "repository_state",
        "working_tree_binding",
    }:
        raise RegistryError(
            "active Component Registry source baseline retains predecessor "
            "route authority"
        )
    binding = baseline.get("working_tree_binding")
    if (
        not isinstance(binding, Mapping)
        or set(binding) != {"mode", "scope", "sha256"}
        or binding.get("mode")
        != "active_revision_plus_embedded_route"
        or binding.get("scope")
        != "complete_embedded_component_registry_route"
        or binding.get("sha256")
        != _route_source_binding(
            str(baseline.get("repository_revision") or ""),
            route,
        )
    ):
        raise RegistryError(
            "active Component Registry source binding differs from its "
            "embedded routing authority"
        )

    provenance = routing.get("predecessor_provenance")
    if not isinstance(provenance, Mapping) or set(provenance) != {
        "schema_version",
        "complete",
        "authority_effect",
        "records",
        "migration_alias_ids",
        "verification_ids",
    }:
        raise RegistryError(
            "active routing predecessor provenance is not a closed envelope"
        )
    if (
        provenance.get("schema_version") != 1
        or provenance.get("complete") is not True
        or provenance.get("authority_effect")
        != "historical_provenance_only_no_runtime_read"
        or provenance.get("migration_alias_ids")
        != ROUTING_PREDECESSOR_ALIAS_IDS
        or provenance.get("verification_ids")
        != ROUTING_PREDECESSOR_VERIFICATION_IDS
    ):
        raise RegistryError(
            "active routing predecessor provenance has invalid authority state"
        )
    records = provenance.get("records")
    if (
        not isinstance(records, Mapping)
        or set(records) != set(ROUTING_PREDECESSOR_IDS)
    ):
        raise RegistryError(
            "active routing predecessor provenance identities differ"
        )
    document_entries = registry["operational_documents"]["entries"]
    alias_entries = registry["aliases_and_migrations"]["entries"]
    for identity in ROUTING_PREDECESSOR_IDS:
        record = records.get(identity)
        expected_path = ROUTING_PREDECESSOR_PATHS[identity]
        if not isinstance(record, Mapping) or set(record) != {
            "stable_id",
            "artifact_kind",
            "historical_path",
            "archived_path",
            "sha256",
            "source_schema_version",
            "state",
            "retirement_proof",
        }:
            raise RegistryError(
                f"active predecessor {identity} provenance fields differ"
            )
        if (
            record.get("stable_id") != identity
            or record.get("artifact_kind")
            != expected_path["artifact_kind"]
            or record.get("historical_path")
            != expected_path["historical_path"]
            or record.get("archived_path")
            != expected_path["archived_path"]
            or record.get("source_schema_version")
            != expected_path["source_schema_version"]
            or record.get("state")
            != "archived_retired_provenance_only"
            or SHA256_RE.fullmatch(str(record.get("sha256") or ""))
            is None
        ):
            raise RegistryError(
                f"active predecessor {identity} provenance is invalid"
            )
        approval = registry["approval"]["value"]
        if record.get("retirement_proof") != {
            "proof_type": "authenticated_activation_cutover",
            "governance_change_id": approval["governance_change_id"],
            "implementation_contract_id": approval[
                "implementation_contract_id"
            ],
            "owner_review_reference": approval[
                "owner_review_reference"
            ],
        }:
            raise RegistryError(
                f"active predecessor {identity} retirement proof differs "
                "from the activation authority"
            )
        document = document_entries.get(identity)
        if (
            not isinstance(document, Mapping)
            or document.get("canonical_path")
            != expected_path["archived_path"]
            or document.get("authority_role")
            != "archived_predecessor"
            or document.get("retention_posture") != "archived"
            or document.get("digest_policy") != "provenance_only"
            or document.get("sha256") != record.get("sha256")
            or document.get("dependencies") != []
            or document.get("consumers") != []
            or document.get("current_status")
            != {
                "state": "known",
                "value": "retired",
            }
        ):
            raise RegistryError(
                f"active predecessor {identity} catalog record is not "
                "provenance-only"
            )
    for alias_id, identity in zip(
        ROUTING_PREDECESSOR_ALIAS_IDS,
        ROUTING_PREDECESSOR_IDS,
        strict=True,
    ):
        alias = alias_entries.get(alias_id)
        expected_path = ROUTING_PREDECESSOR_PATHS[identity]
        if (
            not isinstance(alias, Mapping)
            or alias.get("stable_component_id") != identity
            or alias.get("source_path")
            != expected_path["historical_path"]
            or alias.get("target_path") != expected_path["archived_path"]
        ):
            raise RegistryError(
                f"active predecessor {identity} migration provenance differs"
            )

    readable = routing.get("readable_representation")
    if not isinstance(readable, Mapping) or set(readable) != {
        "representation_id",
        "binding_kind",
        "source_registry_revision",
        "generated_from",
        "authority_effect",
        "executable",
    }:
        raise RegistryError(
            "active routing readable representation binding is not closed"
        )
    expected_revision_binding = (
        f"component_registry_revision:{registry['registry_revision']}"
    )
    if readable != {
        "representation_id": "human_readable_context_routing",
        "binding_kind": "component_registry_revision",
        "source_registry_revision": registry["registry_revision"],
        "generated_from": "embedded_context_routing",
        "authority_effect": "none",
        "executable": False,
    }:
        raise RegistryError(
            "active routing readable representation is not exact-revision "
            "bound and nonauthoritative"
        )
    representation = registry["representations"]["entries"].get(
        "human_readable_context_routing"
    )
    if (
        not isinstance(representation, Mapping)
        or representation.get("representation_type")
        != "human_readable_routing"
        or representation.get("canonical_document_id")
        != "COMPONENT-REGISTRY"
        or representation.get("canonical_path")
        != (
            "framework/project/interfaces/project-console/data/"
            "component-registry.js"
        )
        or representation.get("source_revision_binding")
        != expected_revision_binding
        or representation.get("state") != "active"
    ):
        raise RegistryError(
            "active readable routing representation disagrees with its "
            "Component Registry revision binding"
        )


