def _validate_reference_baseline_evidence(
    readiness: Mapping[str, Any],
    registry: Mapping[str, Any],
    *,
    root: Path,
) -> None:
    evidence = readiness.get("reference_dispositions")
    if (
        not isinstance(evidence, Mapping)
        or set(evidence)
        != {
            "complete",
            "terminal_self_exclusion",
            "historical_preflight",
            "replacement_baseline",
        }
        or evidence.get("complete") is not True
    ):
        raise RegistryError("reference baseline evidence fields differ")
    if evidence.get("terminal_self_exclusion") != {
        "path": ACTIVATION_READINESS_RECEIPT_PATH,
        "reason": "terminal_self_exclusion",
        "requirement_closure_scanned": True,
        "authority_effect": "none",
    }:
        raise RegistryError("terminal reference self-exclusion differs")
    historical = evidence.get("historical_preflight")
    if historical != HISTORICAL_REFERENCE_EVIDENCE:
        raise RegistryError(
            "historical reference evidence differs from count-only authority"
        )
    replacement = evidence.get("replacement_baseline")
    expected_replacement_fields = {
        "complete",
        "identity_completeness",
        "identity_preservation_claim",
        "disposition_classifier",
        "finding_count",
        "state_counts",
        "alias_counts",
        "quiescence",
        "bindings",
        "items",
    }
    if (
        not isinstance(replacement, Mapping)
        or set(replacement) != expected_replacement_fields
        or replacement.get("complete") is not True
        or replacement.get("identity_completeness") != "complete"
        or replacement.get("identity_preservation_claim") is not False
        or not isinstance(replacement.get("items"), list)
    ):
        raise RegistryError("replacement reference baseline fields differ")
    items = replacement["items"]
    if replacement.get("finding_count") != len(items):
        raise RegistryError("replacement reference baseline count differs")
    classifier = replacement.get("disposition_classifier")
    if (
        not isinstance(classifier, Mapping)
        or set(classifier)
        != {
            "schema_version",
            "complete",
            "source_revision",
            "disposition_counts",
        }
        or classifier.get("schema_version")
        != REFERENCE_DISPOSITION_CLASSIFIER_VERSION
        or classifier.get("complete") is not True
        or classifier.get("disposition_counts")
        != REFERENCE_DISPOSITION_COUNTS
    ):
        raise RegistryError(
            "replacement reference disposition classifier differs"
        )
    reference_ids: list[str] = []
    for item in items:
        if (
            not isinstance(item, Mapping)
            or set(item)
            != {
                "reference_id",
                "path",
                "line",
                "alias_id",
                "state",
                "disposition",
            }
            or item.get("state")
            != "requires_rewrite_or_historical_classification"
        ):
            raise RegistryError("replacement reference item fields differ")
        if item.get("disposition") not in REFERENCE_DISPOSITION_COUNTS:
            raise RegistryError(
                "replacement reference item disposition differs"
            )
        reference_ids.append(str(item["reference_id"]))
    if len(reference_ids) != len(set(reference_ids)):
        raise RegistryError("replacement reference IDs are not unique")
    state_counts = dict(
        sorted(Counter(item["state"] for item in items).items())
    )
    alias_counts = dict(
        sorted(Counter(item["alias_id"] for item in items).items())
    )
    if replacement.get("state_counts") != state_counts:
        raise RegistryError("replacement reference state counts differ")
    if replacement.get("alias_counts") != alias_counts:
        raise RegistryError("replacement reference alias counts differ")
    for alias_id, historical_count in (
        HISTORICAL_REFERENCE_ALIAS_COUNTS.items()
    ):
        if alias_counts.get(alias_id, 0) < historical_count:
            raise RegistryError(
                "replacement reference baseline removed unapproved "
                f"{alias_id} references"
            )

    bindings = replacement.get("bindings")
    expected_binding_fields = {
        "algorithm_schema_version",
        "audit_implementation_sha256",
        "component_registry_sha256",
        "predecessor_route_source_sha256",
        "repository_revision",
        "source_working_tree_binding_sha256",
        "input_manifest",
        "input_manifest_sha256",
        "audit_result_sha256",
        "sorted_identity_set_sha256",
    }
    if not isinstance(bindings, Mapping) or set(bindings) != (
        expected_binding_fields
    ):
        raise RegistryError("replacement reference bindings differ")
    if (
        bindings.get("algorithm_schema_version")
        != REFERENCE_AUDIT_SCHEMA_VERSION
    ):
        raise RegistryError("replacement reference authority binding differs")
    manifest = bindings.get("input_manifest")
    if not isinstance(manifest, Mapping):
        raise RegistryError("replacement reference input manifest is absent")
    if bindings.get("input_manifest_sha256") != manifest.get(
        "canonical_sha256"
    ):
        raise RegistryError("replacement reference input binding differs")
    quiescence = replacement.get("quiescence")
    if quiescence != {
        "complete": True,
        "pre_generation_manifest_sha256": manifest["canonical_sha256"],
        "post_generation_manifest_sha256": manifest["canonical_sha256"],
        "identical": True,
    }:
        raise RegistryError("replacement reference quiescence proof differs")
    findings_without_disposition = [
        {
            key: value
            for key, value in item.items()
            if key != "disposition"
        }
        for item in items
    ]
    audit_result = {
        "complete": True,
        "algorithm_schema_version": REFERENCE_AUDIT_SCHEMA_VERSION,
        "input_manifest_sha256": manifest["canonical_sha256"],
        "finding_count": len(items),
        "findings": findings_without_disposition,
    }
    if bindings.get("audit_result_sha256") != hashlib.sha256(
        canonical_json(audit_result).encode("utf-8")
    ).hexdigest():
        raise RegistryError("replacement reference audit-result digest differs")
    sorted_ids = sorted(reference_ids)
    if bindings.get("sorted_identity_set_sha256") != hashlib.sha256(
        canonical_json(sorted_ids).encode("utf-8")
    ).hexdigest():
        raise RegistryError("replacement reference identity-set digest differs")
    classified = classify_reference_dispositions(
        items,
        root=root,
        source_revision=str(classifier["source_revision"]),
        input_manifest=manifest,
    )
    if classified != items:
        raise RegistryError(
            "replacement reference disposition classification differs"
        )
    source_revision = str(classifier["source_revision"])
    baseline_registry_text = _reference_baseline_text(
        root=root,
        revision=source_revision,
        path=CANONICAL_REGISTRY_PATH,
    )
    baseline_registry = json.loads(baseline_registry_text)
    baseline_tool_text = _reference_baseline_text(
        root=root,
        revision=source_revision,
        path="scripts/component_registry.py",
    )
    predecessor_route_text = _reference_baseline_text(
        root=root,
        revision=source_revision,
        path=ROUTING_PREDECESSOR_PATHS[
            "context_routes_source"
        ]["historical_path"],
    )
    if (
        bindings.get("audit_implementation_sha256")
        != hashlib.sha256(baseline_tool_text.encode("utf-8")).hexdigest()
        or bindings.get("component_registry_sha256")
        != _canonical_registry_digest(baseline_registry)
        or bindings.get("predecessor_route_source_sha256")
        != hashlib.sha256(
            predecessor_route_text.encode("utf-8")
        ).hexdigest()
        or bindings.get("repository_revision")
        != baseline_registry["source_baseline"]["repository_revision"]
        or bindings.get("source_working_tree_binding_sha256")
        != baseline_registry["source_baseline"][
            "working_tree_binding"
        ]["sha256"]
    ):
        raise RegistryError(
            "replacement reference frozen authority binding differs"
        )


def _validate_activation_readiness_receipts(
    registry: Mapping[str, Any],
    *,
    root: Path,
) -> None:
    _validate_activation_readiness(registry, root=root)
    namespace = registry["activation_readiness"]
    if registry.get("status") == "active":
        return
    if root.resolve() != ROOT.resolve():
        return
    closure = _load_public_readiness_receipt(
        root,
        REQUIREMENT_CLOSURE_RECEIPT_PATH,
        "Component Registry requirement closure receipt",
    )
    validate_requirement_closure_receipt(closure)
    readiness = _load_public_readiness_receipt(
        root,
        ACTIVATION_READINESS_RECEIPT_PATH,
        "Component Registry activation readiness receipt",
    )
    expected_fields = {
        "schema_version",
        "receipt_id",
        "design_id",
        "design_revision",
        "design_authorities",
        "registry_binding",
        "future_tree",
        "created_artifacts",
        "reference_dispositions",
        "ignored_artifacts",
        "simulated_active",
        "requirement_closure",
        "console_generation_readback",
        "stage_boundaries",
        "publication_sequence",
    }
    if not isinstance(readiness, Mapping) or set(readiness) != expected_fields:
        raise RegistryError("activation readiness receipt fields differ")
    binding = readiness.get("registry_binding")
    if binding != {
        "registry_id": registry["registry_id"],
        "registry_revision": registry["registry_revision"],
        "status": "candidate",
        "authoritative": False,
        "executable": False,
        "canonical_sha256": _canonical_registry_digest(registry),
    }:
        raise RegistryError("activation readiness registry binding differs")
    if (
        readiness.get("schema_version") != 1
        or readiness.get("receipt_id")
        != "component_registry_stage1_activation_readiness"
        or readiness.get("design_id") != ACTIVATION_READINESS_DESIGN_ID
        or readiness.get("design_revision")
        != ACTIVATION_READINESS_DESIGN_REVISION
    ):
        raise RegistryError("activation readiness receipt identity differs")
    if readiness.get("design_authorities") != {
        "candidate_activation_readiness": {
            "design_id": ACTIVATION_READINESS_DESIGN_ID,
            "design_revision": ACTIVATION_READINESS_DESIGN_REVISION,
            "role": "candidate_readiness_parent_design",
        },
        "ultra_acceptance_corrections": {
            "design_id": ULTRA_ACCEPTANCE_CORRECTIONS_DESIGN_ID,
            "design_revision": ULTRA_ACCEPTANCE_CORRECTIONS_DESIGN_REVISION,
            "role": "terminal_console_readback_and_acceptance_correction",
        },
    }:
        raise RegistryError("activation readiness design authorities differ")
    _validate_reference_baseline_evidence(
        readiness,
        registry,
        root=root,
    )
    requirement = readiness.get("requirement_closure")
    closure_path = _contained_file(
        root,
        REQUIREMENT_CLOSURE_RECEIPT_PATH,
        "Component Registry requirement closure receipt",
    )
    if requirement != {
        "path": REQUIREMENT_CLOSURE_RECEIPT_PATH,
        "sha256": _sha256(closure_path),
        "requirement_count": REQUIREMENT_COUNT,
        "complete_catalog": True,
    }:
        raise RegistryError("activation readiness closure binding differs")
    if readiness.get("console_generation_readback") != (
        build_console_generation_readback(root=root)
    ):
        raise RegistryError(
            "activation readiness Console generation readback differs"
        )
    if readiness.get("stage_boundaries") != namespace["stage_boundaries"]:
        raise RegistryError("activation readiness stage boundaries differ")
    if (
        readiness.get("publication_sequence")
        != namespace["publication_sequence"]
    ):
        raise RegistryError(
            "activation readiness publication sequence differs"
        )


