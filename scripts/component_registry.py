def _load_public_readiness_receipt(
    root: Path,
    relative: str,
    label: str,
) -> dict[str, Any]:
    path = _contained_file(root, relative, label)
    try:
        if path.stat().st_size > 8 * 1024 * 1024:
            raise RegistryError(f"{label} exceeds its bounded size")
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise RegistryError(f"{label} is unavailable or malformed") from exc
    if not isinstance(value, dict):
        raise RegistryError(f"{label} must be a JSON object")
    return value


def validate_requirement_closure_receipt(
    receipt: Mapping[str, Any],
) -> None:
    expected_fields = {
        "schema_version",
        "receipt_id",
        "design_id",
        "design_revision",
        "source_design",
        "implementation_blueprint",
        "requirement_count",
        "requirements_sha256",
        "complete_catalog",
        "rows",
    }
    if set(receipt) != expected_fields:
        raise RegistryError("requirement closure receipt fields differ")
    if (
        receipt.get("schema_version") != 1
        or receipt.get("receipt_id")
        != "component_registry_stage1_requirement_closure"
        or receipt.get("design_id") != ACTIVATION_READINESS_DESIGN_ID
        or receipt.get("design_revision")
        != ACTIVATION_READINESS_DESIGN_REVISION
        or receipt.get("requirement_count") != REQUIREMENT_COUNT
        or receipt.get("requirements_sha256") != REQUIREMENT_TEXTS_SHA256
        or receipt.get("complete_catalog") is not True
    ):
        raise RegistryError("requirement closure receipt identity differs")
    if receipt.get("source_design") != {
        "document_id": SOURCE_DESIGN_ID,
        "revision": SOURCE_DESIGN_REVISION,
        "sha256": SOURCE_DESIGN_SHA256,
        "section": "Registry enforcement requirements",
        "requirement_count": REQUIREMENT_COUNT,
        "normalization": "markdown_continuation_whitespace_only",
    }:
        raise RegistryError("requirement closure source design differs")
    if receipt.get("implementation_blueprint") != {
        "document_id": IMPLEMENTATION_BLUEPRINT_ID,
        "revision": IMPLEMENTATION_BLUEPRINT_REVISION,
        "sha256": IMPLEMENTATION_BLUEPRINT_SHA256,
        "closure_matrix_lines": "1182-1205",
    }:
        raise RegistryError(
            "requirement closure implementation blueprint differs"
        )
    rows = receipt.get("rows")
    if not isinstance(rows, list) or len(rows) != REQUIREMENT_COUNT:
        raise RegistryError(
            "requirement closure must contain exactly 77 rows"
        )
    expected_row_fields = {
        "cr_id",
        "ordinal",
        "design_requirement",
        "implementation_locations",
        "verification_ids",
        "pre_activation_result",
        "canonical_readback_result",
        "exception_status",
        "approved_deferral",
        "receipt_provenance_reference",
    }
    seen_requirements: set[str] = set()
    for expected_ordinal, row in enumerate(rows, start=1):
        if not isinstance(row, Mapping) or set(row) != expected_row_fields:
            raise RegistryError(
                f"CR-{expected_ordinal:03d} closure fields differ"
            )
        expected_id = f"CR-{expected_ordinal:03d}"
        requirement = row.get("design_requirement")
        if (
            row.get("cr_id") != expected_id
            or row.get("ordinal") != expected_ordinal
            or not isinstance(requirement, str)
            or not requirement.strip()
            or requirement in seen_requirements
        ):
            raise RegistryError(f"{expected_id} identity or text differs")
        seen_requirements.add(requirement)
        for field in ("implementation_locations", "verification_ids"):
            values = row.get(field)
            if (
                not isinstance(values, list)
                or not values
                or len(values) != len(set(values))
                or not all(isinstance(value, str) and value for value in values)
            ):
                raise RegistryError(f"{expected_id} {field} is incomplete")
        if row.get("canonical_readback_result") != (
            "pending_activation_readback"
        ):
            raise RegistryError(
                f"{expected_id} canonical readback result differs"
            )
        if row.get("exception_status") != "":
            raise RegistryError(f"{expected_id} has an activation exception")
        deferral = row.get("approved_deferral")
        if deferral not in {None, "deferred_by_approved_stage_boundary"}:
            raise RegistryError(f"{expected_id} deferral is not approved")
        result = row.get("pre_activation_result")
        if not isinstance(result, str) or not result:
            raise RegistryError(
                f"{expected_id} pre-activation result is absent"
            )
        if (
            result == "deferred_by_approved_stage_boundary"
            or "deferred_stage2" in result
            or "mutation_not_activated" in result
        ) and deferral != "deferred_by_approved_stage_boundary":
            raise RegistryError(
                f"{expected_id} deferred result lacks the exact boundary"
            )
        if row.get("receipt_provenance_reference") != (
            ACTIVATION_READINESS_RECEIPT_PATH
        ):
            raise RegistryError(
                f"{expected_id} readiness provenance differs"
            )
    actual_text_digest = hashlib.sha256(
        json.dumps(
            [row["design_requirement"] for row in rows],
            ensure_ascii=False,
            separators=(",", ":"),
        ).encode("utf-8")
    ).hexdigest()
    if actual_text_digest != REQUIREMENT_TEXTS_SHA256:
        raise RegistryError("requirement closure normalized text digest differs")


