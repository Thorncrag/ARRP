def refresh_activation_readiness_receipt(
    registry: Mapping[str, Any],
    *,
    root: Path,
) -> dict[str, Any]:
    """Atomically refresh the fixed candidate-readiness receipt."""

    if root.resolve() != ROOT.resolve():
        raise RegistryError(
            "production readiness refresh requires the canonical repository"
        )
    receipt = build_activation_readiness_receipt(registry, root=root)
    destination = _contained_file(
        root,
        ACTIVATION_READINESS_RECEIPT_PATH,
        "Component Registry activation readiness receipt",
    )
    content = json.dumps(receipt, ensure_ascii=False, indent=2) + "\n"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.refresh-",
        dir=destination.parent,
    )
    temporary = Path(temporary_name)
    try:
        os.fchmod(descriptor, destination.stat().st_mode & 0o777)
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            descriptor = -1
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        written = _read_json(temporary)
        if written != receipt:
            raise RegistryError(
                "activation readiness receipt changed during serialization"
            )
        os.replace(temporary, destination)
    except Exception:
        if descriptor >= 0:
            os.close(descriptor)
        raise
    return receipt


